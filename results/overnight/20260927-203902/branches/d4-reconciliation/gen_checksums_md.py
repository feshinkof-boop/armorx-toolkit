#!/usr/bin/env python3
import json, os
OUT = "/home/salamanka/armorx-lab/results/overnight/20260927-203902/branches/d4-reconciliation"
raw = json.load(open(os.path.join(OUT,"checksums-raw.json")))
rows = raw["rows"]

lines = []
lines.append("# D4 / frame checksum verification (arithmetic, recomputed)")
lines.append("")
lines.append("Every frame below was decomposed byte-by-byte and its trailing checksum recomputed as")
lines.append("`sum(all bytes except the last) & 0xFF` (project convention). The **recorded** value is what the")
lines.append("source file / document states. A corpus sweep of **227** A5/A4 frame strings across")
lines.append("`armorx-lab/results`, `baselines`, virtual-peripheral logs, frida traces, `armorx_research` and")
lines.append("`armorx-re/repo` found **exactly two** checksum deviations, both the 2.22 robustness probes")
lines.append("(deliberately malformed). **No accidental checksum error exists in the corpus.**")
lines.append("")
lines.append("Convention note: in every recognized frame the LEN byte equals the **total frame length**")
lines.append("(`LEN == len(frame)`), consistent with the project's own statement in `d4-reconstruction.md` §6.")
lines.append("The task brief's phrasing (\"LEN counts the bytes after it\") does **not** match the corpus.")
lines.append("")
lines.append("## Primary frames")
lines.append("")
lines.append("| id | frame bytes | LEN | total | recomputed cks | recorded cks | match? | provenance |")
lines.append("|---|---|---:|---:|---|---|---|---|")
for r in rows:
    m = "—" if r["recorded_cks"] is None else ("**MATCH**" if r["status"]=="MATCH" else f"**{r['status']}**")
    lines.append(f"| {r['id']} | `{r['hex']}` | {r['len_byte']} | {r['total_bytes']} | {r['recomputed_cks'] or '—'} | {r['recorded_cks'] or '—'} | {m} | {r['provenance']} |")
lines.append("")
lines.append("## Deviations (both deliberate; flagged, not corrected)")
lines.append("")
lines.append("| frame | recorded cks | recomputed cks | reason |")
lines.append("|---|---|---|---|")
lines.append("| `A5 06 D4 00 00 80` | `0x80` | `0x7F` | 2.22 robustness probe `--d4-reply-mode bad-checksum`; the wrong byte is the *point* (proves the app ignores the inbound D4 checksum) |")
lines.append("| `A5 04 D4 00` | *(none)* | *(none)* | 2.22 robustness probe `--d4-reply-mode truncated`; 4 bytes only, checksum absent by design (proves the index-4 read has no length guard) |")
lines.append("")
lines.append("## Corpus-wide sweep result")
lines.append("")
sweep = json.load(open(os.path.join(OUT,"corpus-sweep.json")))
lines.append(f"- frames recognized: **{sweep['recognized']}**")
lines.append(f"- checksum mismatches: **{len(sweep['mismatches'])}** (both the deliberate probes above)")
lines.append("- no other A5/A4 frame in the corpus carries a wrong trailing byte.")
lines.append("")
open(os.path.join(OUT,"checksums-verified.md"),"w").write("\n".join(lines))
print("wrote checksums-verified.md", len(rows), "primary rows")
